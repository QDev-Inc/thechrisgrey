/**
 * Account pin for Node scripts that shell out to the AWS CLI.
 *
 * The site lives in Christian Perez - Personal Account (973662476023). Never
 * trust an ambient AWS_PROFILE: these helpers accept only qdev-personal and
 * verify its account before a script reads or changes AWS state.
 */
import { execFileSync } from 'node:child_process';

const DEFAULT_PROFILE = 'qdev-personal';
const ACCOUNT_ID = '973662476023';
const FOUNDATION_STACK = 'thechrisgrey-foundation';
const FOUNDATION_REGION = 'us-east-1';

/**
 * Resolve THECHRISGREY_AWS_PROFILE, export it for this process and child AWS
 * calls, and verify it targets the personal account.
 */
export function pinAwsAccount() {
  const profile = process.env.THECHRISGREY_AWS_PROFILE || DEFAULT_PROFILE;
  if (profile !== DEFAULT_PROFILE) {
    console.error(`AWS preflight: THECHRISGREY_AWS_PROFILE='${profile}' is not this repo's home.`);
    console.error(`  This repo runs only as ${DEFAULT_PROFILE} (Christian Perez - Personal Account ${ACCOUNT_ID}).`);
    process.exit(1);
  }

  process.env.THECHRISGREY_AWS_PROFILE = profile;
  process.env.AWS_PROFILE = profile;
  let actual;
  try {
    actual = execFileSync('aws', ['sts', 'get-caller-identity', '--query', 'Account', '--output', 'text'], {
      encoding: 'utf8',
    }).trim();
  } catch {
    console.error(
      `AWS preflight: no working credentials for profile '${profile}'. Try: aws sso login --profile ${profile}`,
    );
    process.exit(1);
  }
  if (actual !== ACCOUNT_ID) {
    console.error(
      `AWS preflight: profile '${profile}' resolved to account ${actual}, expected ${ACCOUNT_ID}. Refusing to continue.`,
    );
    process.exit(1);
  }

  console.error(`AWS preflight: profile ${profile}, account ${actual}`);
  return { profile, account: ACCOUNT_ID };
}

/**
 * Read the current durable-resource identifiers from the foundation stack.
 * Resource IDs are generated by CloudFormation, so callers must not hard-code
 * an earlier account's Knowledge Base or data-source identifiers.
 */
export function getFoundationOutputs() {
  try {
    const output = execFileSync(
      'aws',
      [
        'cloudformation',
        'describe-stacks',
        '--region',
        FOUNDATION_REGION,
        '--stack-name',
        FOUNDATION_STACK,
        '--query',
        'Stacks[0].Outputs',
        '--output',
        'json',
      ],
      { encoding: 'utf8' },
    );
    const values = Object.fromEntries(JSON.parse(output).map(({ OutputKey, OutputValue }) => [OutputKey, OutputValue]));
    const required = [
      'PodcastKnowledgeBaseId',
      'PodcastKnowledgeBaseDataSourceId',
      'PodcastKnowledgeBaseSourceBucketName',
    ];
    if (required.some((key) => !values[key])) {
      throw new Error(`missing required outputs: ${required.filter((key) => !values[key]).join(', ')}`);
    }
    return values;
  } catch (error) {
    console.error(
      `AWS preflight: could not read ${FOUNDATION_STACK} outputs: ${error instanceof Error ? error.message : String(error)}`,
    );
    process.exit(1);
  }
}
