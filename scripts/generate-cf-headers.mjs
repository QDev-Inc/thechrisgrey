/**
 * Generates dist/_headers and dist/404.html for Cloudflare Pages.
 *
 * SINGLE SOURCE OF TRUTH: the security headers come from customHttp.yml's
 * `**\/*` rule, the same block Amplify Hosting reads. Editing the CSP there
 * updates both hosts. Do not hand-edit dist/_headers.
 *
 * WHY THE CACHE RULES ARE NOT COPIED FROM customHttp.yml
 * Amplify matches the on-disk file (`*.html`). Pages serves prerendered HTML at
 * its EXTENSIONLESS path (`/about.html` is served as `/about`), so an `*.html`
 * pattern never matches a real request. Pages also MERGES every matching rule
 * and comma-joins duplicate header names, so a broad `/*` Cache-Control plus a
 * narrow `/assets/*` one would emit the nonsense value
 * `no-cache, must-revalidate, public, max-age=31536000, immutable`.
 * Instead we let Pages' own HTML default stand (`public, max-age=0,
 * must-revalidate` — equivalent to the intended `no-cache, must-revalidate`,
 * and likewise bfcache-safe because it is not `no-store`) and only override
 * caching on non-overlapping, content-hashed or static asset paths.
 */
import { readFileSync, writeFileSync, existsSync, copyFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = resolve(ROOT, 'dist');
const MAX_LINE = 2000; // Cloudflare Pages: per-line limit in _headers
const MAX_RULES = 100; // Cloudflare Pages: max header rules

/** Pull the `pattern: '**\/*'` header block out of customHttp.yml. */
function readSecurityHeaders() {
  const yml = readFileSync(resolve(ROOT, 'customHttp.yml'), 'utf8');
  const block = yml.split(/- pattern:/).find((b) => /^\s*'\*\*\/\*'/.test(b));
  if (!block) throw new Error('customHttp.yml: no `**/*` rule found');
  const out = [];
  const re = /- key: '([^']+)'\s*\n\s*value: (?:'([^']*)'|"([\s\S]*?)")\s*\n/g;
  let m;
  while ((m = re.exec(block)) !== null) out.push([m[1], m[2] ?? m[3]]);
  if (!out.some(([k]) => k === 'Content-Security-Policy')) {
    throw new Error('customHttp.yml: `**/*` rule is missing Content-Security-Policy');
  }
  return out;
}

const security = readSecurityHeaders();
const IMMUTABLE = 'public, max-age=31536000, immutable';
const WEEK = 'public, max-age=604800';

const rules = [
  // Pages adds `Access-Control-Allow-Origin: *` to every asset by default.
  // Amplify does not, and it contradicts Cross-Origin-Resource-Policy:
  // same-origin, so detach it rather than silently loosening the origin policy.
  ['/*', [...security.map(([k, v]) => `${k}: ${v}`), '! Access-Control-Allow-Origin']],
  ['/assets/*', [`Cache-Control: ${IMMUTABLE}`]], // content-hashed js/css/img
  ['/fonts/*', [`Cache-Control: ${IMMUTABLE}`]],
  ['/*.glb', [`Cache-Control: ${WEEK}`]],
  ['/*.png', [`Cache-Control: ${WEEK}`]],
  ['/*.webp', [`Cache-Control: ${WEEK}`]],
  ['/*.jpeg', [`Cache-Control: ${WEEK}`]],
  ['/sitemap.xml', ['Cache-Control: public, max-age=3600']],
  ['/rss.xml', ['Cache-Control: public, max-age=3600']],
];

const body = rules.map(([p, hs]) => `${p}\n${hs.map((h) => `  ${h}`).join('\n')}`).join('\n\n');
const text = `# GENERATED by scripts/generate-cf-headers.mjs - do not edit.\n# Security headers are sourced from customHttp.yml.\n\n${body}\n`;

// Fail the build rather than let Cloudflare silently drop an over-long line.
const tooLong = text.split('\n').filter((l) => l.length > MAX_LINE);
if (tooLong.length) {
  throw new Error(
    `_headers: ${tooLong.length} line(s) exceed Cloudflare's ${MAX_LINE}-char limit ` +
      `(longest ${Math.max(...tooLong.map((l) => l.length))}). Shorten the CSP in customHttp.yml.`,
  );
}
if (rules.length > MAX_RULES) throw new Error(`_headers: ${rules.length} rules exceed ${MAX_RULES}`);
if (!existsSync(DIST)) throw new Error('dist/ not found - run the build first');
writeFileSync(resolve(DIST, '_headers'), text);

// Without a top-level 404.html, Pages switches into SPA mode and answers EVERY
// unknown path with index.html and a 200, turning typos and dead links into
// indexable soft-404s. The shell renders the NotFound route client-side; Pages
// serves it with a real 404 status.
copyFileSync(resolve(DIST, 'index.html'), resolve(DIST, '404.html'));

const cspLen = security.find(([k]) => k === 'Content-Security-Policy')[1].length;
console.log(
  `generate-cf-headers: ${rules.length} rules, ${security.length} security headers, ` +
    `CSP ${cspLen} chars -> dist/_headers + dist/404.html`,
);
